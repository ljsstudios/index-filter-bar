import orders from "../data/orders.json";
import products from "../data/products.json";

/** The demo store's stock locations. */
export const LOCATIONS = ["Shop floor", "Warehouse", "Pop-up store"] as const;
export type Location = (typeof LOCATIONS)[number];

export interface Stock {
  available: number;
  committed: number;
  unavailable: number;
  onHand: number;
  incoming: number;
  /** Where it's kept at the location, "" for none. */
  bin: string;
}

export interface Variant {
  id: string;
  title: string;
  sku: string;
  price: number;
  weightLb: number;
  barcode: string;
  fulfillable: boolean;
  stock: Record<Location, Stock>;
}

export interface Product {
  id: string;
  title: string;
  handle: string;
  image: string | null;
  vendor: string;
  productType: string;
  category: string;
  tags: string[];
  collections: string[];
  status: "active" | "draft" | "archived";
  salesChannels: string[];
  /** Generated: a date this many days before today, so presets stay meaningful. */
  createdAt: Date;
  variants: Variant[];
  /** Available at every location, across every variant. */
  inventory: number;
}

const DAY = 24 * 60 * 60 * 1000;
const now = Date.now();

/**
 * The demo's catalog: mock.shop's sample products, with statuses, dates, SKUs,
 * weights and stock generated by scripts/generate-demo-data.ts.
 */
export const PRODUCTS: Product[] = products.map((product) => ({
  ...product,
  status: product.status as Product["status"],
  createdAt: new Date(now - product.createdDaysAgo * DAY),
  variants: product.variants as Variant[],
  inventory: product.variants.reduce(
    (sum, variant) =>
      sum +
      LOCATIONS.reduce(
        (s, location) => s + (variant.stock as Variant["stock"])[location].available,
        0,
      ),
    0,
  ),
}));

/** Every distinct value, sorted, as filter choices. */
export const choices = (values: Iterable<string>) =>
  [...new Set(values)]
    .filter(Boolean)
    .sort((a, b) => a.localeCompare(b))
    .map((value) => ({ value, label: value }));

export interface OrderLine {
  productId: string;
  variantId: string;
  title: string;
  variantTitle: string;
  quantity: number;
  price: number;
  weightLb: number;
}

export type Order = Omit<(typeof orders)[number], "createdDaysAgo" | "fulfillByDaysAgo"> & {
  createdAt: Date;
  fulfillBy: Date;
  lines: OrderLine[];
};

/** The demo's orders, generated from the catalog's active products. */
export const ORDERS: Order[] = orders.map(({ createdDaysAgo, fulfillByDaysAgo, ...order }) => ({
  ...order,
  createdAt: new Date(now - createdDaysAgo * DAY),
  fulfillBy: new Date(now - fulfillByDaysAgo * DAY),
}));

/** Every variant, with its product, for the Inventory page and the Product filter. */
export const VARIANTS = PRODUCTS.flatMap((product) =>
  product.variants.map((variant) => ({ product, variant })),
);

/** "Snowboard" or "Snowboard - Large", as the admin names a variant. */
export const variantName = (product: Product, variant: Variant) =>
  variant.title === "Default Title" ? product.title : `${product.title} - ${variant.title}`;

/** Variants that appear in an order: Inventory links these to their orders. */
export const ORDERED_VARIANTS = new Set(
  ORDERS.flatMap((order) => order.lines.map((l) => l.variantId)),
);
